// String --> Primitive Data Type
// Immutable (characters can't be changed)
// Indexing concept is present..

let string = "Retam Mondal";

// ------------------------------------------------------------------------------
// Indexing
// ------------------------------------------------------------------------------
console.log(string[1]);     // will give index 1 = e
string[2] = "a";            // NOT POSSIBLE!!

// ------------------------------------------------------------------------------
// Basic Operations & Properties
// ------------------------------------------------------------------------------
// 1. Accessing Characters --> string[index]
// 2. Checking Length      --> string.length
// 3. Concatenation        --> +
// 4. Uppercase, Lowercase --> string.toLowerCase()/ string.toUpperCase()
// 5. Substring Exist      --> string.includes(substring)   --> True/ False
// 6. Index Check          --> string.indexOf(substring)