// --- Part 09: Creating and Adding Elements ---
console.log("\n--- Creating & Adding Elements ---");
const body = document.querySelector("body");

// createElement
const newDiv = document.createElement("div");
newDiv.textContent = "I am a newly created DIV!";
newDiv.style.backgroundColor = "lightgreen";
newDiv.style.padding = "10px";
newDiv.style.marginTop = "10px";

// appendChild
body.appendChild(newDiv);

// append & prepend
const p1 = document.createElement("p");
p1.textContent = "Appended text.";
const p2 = document.createElement("p");
p2.textContent = "Prepended text! I am first now.";

body.append(p1, " Just some random raw string appended.");
body.prepend(p2);

// insertBefore
const productList = document.querySelector("#product-list");
const newItem = document.createElement("li");
newItem.textContent = "Inserted Item (Before 3rd child)";
const referenceNode = productList.children[2]; // Product C

productList.insertBefore(newItem, referenceNode);


// --- Part 10: Removing and Cloning Elements ---
console.log("\n--- Removing & Cloning ---");

// remove()
const removeMe = document.querySelector("#h1-remove");
removeMe.remove();

// cloneNode()
const original = document.querySelector("#product-list-one");
const deepClone = original.cloneNode(true);   // Deep clone (with children)
const shallowClone = original.cloneNode(false); // Shallow clone (no children)

deepClone.classList.add("clone");
body.append(deepClone);


