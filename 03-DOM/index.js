// --- Part 02: The Global Objects ---
console.log("--- Global Objects ---");
console.log(window);        // The global window object
console.log(document);      // The DOM document object
console.log(document === window.document); // true


// --- Part 03: Selecting Elements from the DOM ---
console.log("\n--- Selecting Elements ---");

// getElementById
const h1Single = document.getElementById("h1");
console.log("getElementById:", h1Single);

const notFound = document.getElementById("nonexistent");
console.log("Not found:", notFound); // null

// querySelector
const h1Query = document.querySelector("h1");
const headingClass = document.querySelector(".heading");
const inputElement = document.querySelector('input[type="text"]');
const childNode = document.querySelector("div > p");

// querySelectorAll
const allHeadings = document.querySelectorAll("#h1");
console.log("querySelectorAll NodeList:", allHeadings);
console.log("Length of NodeList:", allHeadings.length);

// Iterating through NodeList
allHeadings.forEach((heading, index) => {
    console.log(`Heading ${index + 1}: ${heading.textContent}`);
});

// Convert NodeList to Array
const headingArray = Array.from(allHeadings);
console.log("Is it an array now?", Array.isArray(headingArray));


// --- Part 04: Reading and Modifying Content ---
console.log("\n--- Modifying Content ---");
const contentDemo = document.querySelector("#content-demo");
const hiddenDemo = document.querySelector("#hidden-demo");

// textContent vs innerHTML vs innerText
console.log("textContent:", contentDemo.textContent); // "Hello World"
console.log("innerHTML:", contentDemo.innerHTML);     // "Hello <b>World</b>"
console.log("innerText (ignores hidden):", hiddenDemo.innerText); // "Hello World"
console.log("textContent (shows hidden):", hiddenDemo.textContent); // "Hello Hidden World"

// Writing content
contentDemo.innerHTML = "<b>Bold</b> text generated by JS";


// --- Part 05: Working with Attributes ---
console.log("\n--- Attributes ---");
const attrDemo = document.querySelector("#attr-demo");
const btn = document.querySelector("#btn");

// setAttribute
attrDemo.setAttribute("style", "background-color: pink; font-size: 20px; padding: 10px;");
btn.setAttribute("disabled", "true");
attrDemo.setAttribute("data-custom", "myValue");

// getAttribute
console.log("Get style attribute:", attrDemo.getAttribute("style"));
console.log("Get non-existent:", attrDemo.getAttribute("nonexistent")); // null

// Checking and Removing
console.log("Has disabled?", btn.hasAttribute("disabled")); // true
btn.removeAttribute("disabled"); // Button enabled again
console.log("All attributes of btn:", btn.attributes);


// --- Part 06: Working with Classes ---
console.log("\n--- Classes ---");
const classDemo = document.querySelector("#class-style-demo");

classDemo.classList.add("random");
classDemo.classList.add("highlight", "large-text");
classDemo.classList.remove("random");
classDemo.classList.toggle("primary-bg"); // Adds it since it doesn't exist

